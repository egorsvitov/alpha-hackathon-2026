def is_noise_candidate(
    url: str,
    title: str,
    summary: str | None = None,
    source: str = "",
) -> bool:
    """True, если кандидат является техническим/табличным/таблоидным мусором.

    Вызывается до скачивания полного текста (на этапе ленты) и экономит сетевые
    запросы. Сохраняет все статьи с финансовыми/экономическими/деловыми маркерами.
    """
    low_url = (url or "").lower()
    clean_title = (title or "").strip()
    clean_summary = (summary or "").strip()
    combined = f"{clean_title} {clean_summary}".strip()

    # 1. Не-новостные разделы/таблицы/реестры ЦБ РФ.
    if _CBR_NON_NEWS_URL_RE.search(low_url):
        return True

    # 2. Технические биржевые уведомления Мосбиржи (РЕПО, ценовые коридоры, списки и т.д.).
    is_moex = source in ("moex_rss", "moex_main") or "moex.com" in low_url
    if _MOEX_TECH_TITLE_RE.search(clean_title):
        return True
    if is_moex and _MOEX_TECH_TITLE_RE.search(combined):
        return True

    # 3. Заведомо неделовые рубрики в URL (спорт, шоу-бизнес, криминал, погода, гороскопы).
    if _NON_BUSINESS_URL_RE.search(low_url) and not _BUSINESS_SIGNAL_RE.search(clean_title):
        return True

    # 4. Если сам заголовок явно таблоидный/криминальный/спортивный/погодный и не содержит
    # деловых сигналов — отбрасываем кандидата.
    if (
        clean_title
        and not _BUSINESS_SIGNAL_RE.search(clean_title)
        and _TABLOID_NOISE_RE.search(clean_title)
    ):
        return True

    # 5. Бытовой/криминальный/спортивный/таблоидный шум в связке заголовок+описание.
    return bool(
        combined
        and not _BUSINESS_SIGNAL_RE.search(combined)
        and _TABLOID_NOISE_RE.search(combined)
    )


def is_junk_text(text: str) -> bool:
    """True, если извлечённый текст пуст, слишком короток или состоит из меню сайта."""
    if not text:
        return True
    stripped = text.strip()
    if len(stripped) < 80:
        return True
    # Если текст короткий (< 500 символов) и совпадает с шапкой/футером ЦБ, Мосбиржи или банка.
    if len(stripped) < 500:
        for pat in _JUNK_TEXT_PATTERNS:
            if pat.search(stripped):
                return True
    return False


